import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { RsbuildPluginAPI } from '@lynx-js/rspeedy';
import {
  BASE_PACKAGES,
  type IntlApi,
  intlApiPackages,
  resolveIntlApis,
} from './apis.js';
import { collationData } from './collation-data.js';
import { appLocales, findDataLocale } from './locales.js';

export type IntlModuleOptions = {
  /** The APIs the app asked for, in the `intl` option. */
  readonly apis: readonly IntlApi[];
  /** angular.json's `i18n.sourceLocale`. */
  readonly sourceLocale: string;
  /** The keys of angular.json's `i18n.locales`. */
  readonly locales: readonly string[];
  /** Where the app's packages resolve from. */
  readonly rootPath: string;
  /** The runtime half (runtime.ts), as the plugin's build emits it. */
  readonly runtimePath: string;
};

export type IntlModule = {
  /** The module's source. */
  readonly source: string;
  /**
   * The source of the module it imports first, `./canonical-locales.js`,
   * which adds `Intl.getCanonicalLocales` (see {@link renderIntlModule}).
   */
  readonly canonicalLocalesSource: string;
  /** Each API's locale data files, keyed by the app's locale. */
  readonly dataFiles: ReadonlyMap<IntlApi, ReadonlyMap<string, string>>;
  /** The app's locales FormatJS has no data for, by API. */
  readonly missingLocales: ReadonlyMap<IntlApi, readonly string[]>;
};

/**
 * Where a FormatJS package is installed: the app installs them itself (they
 * are this plugin's optional peer dependencies: with every locale's data,
 * NumberFormat's is 127 MB and DateTimeFormat's 161 MB), so they resolve
 * from the app.
 */
const packageDir = (rootPath: string, name: string): string | undefined => {
  const require = createRequire(path.join(rootPath, 'package.json'));
  try {
    return path.dirname(require.resolve(`${name}/polyfill.js`));
  } catch {
    return undefined;
  }
};

/**
 * Writes the module that adds `Intl` to the Lynx bundle: FormatJS's
 * polyfills for the APIs asked for and those they call, each with the data
 * of the app's locales, then our setup (runtime.ts), which makes them
 * default to the phone's language and time zone and adds `Intl.Collator`.
 *
 * The app's locales are angular.json's `i18n.sourceLocale` and the keys of
 * `i18n.locales`. Lynx apps have one bundle for every language (translations
 * load at runtime), so the bundle has every one's data.
 */
export const renderIntlModule = ({
  apis: requested,
  sourceLocale,
  locales,
  rootPath,
  runtimePath,
}: IntlModuleOptions): IntlModule => {
  const apis = resolveIntlApis(requested);
  const packages = intlApiPackages(apis);
  const tags = appLocales(sourceLocale, locales);
  const dirs = new Map<string, string>();
  const missing: string[] = [];
  for (const name of [...BASE_PACKAGES, ...packages.map((p) => p.package)]) {
    const dir = packageDir(rootPath, name);
    if (dir === undefined) missing.push(name);
    else dirs.set(name, dir);
  }
  if (missing.length > 0) {
    throw new Error(
      `The \`intl\` build option (${requested.join(', ')}) uses FormatJS's polyfills, which aren't installed. Install them: npm install ${missing.join(' ')}`,
    );
  }

  // FormatJS's getCanonicalLocales polyfill is a bundle of its own, with
  // its own copy of CLDR's likely subtags, which intl-locale imports from
  // the package's index too: 166 kB a thread, twice. So the generated
  // module adds the index's function itself, and the two share one copy.
  const canonicalLocalesSource = [
    '// Generated by @blotch/rsbuild-plugin-angular-lynx: Intl.getCanonicalLocales,',
    "// from the module intl-locale imports too, before FormatJS's polyfills.",
    `import { getCanonicalLocales } from ${JSON.stringify(
      path.join(dirs.get(BASE_PACKAGES[0])!, 'index.js'),
    )};`,
    "if (typeof Intl === 'undefined') {",
    "  Object.defineProperty(globalThis, 'Intl', { configurable: true, writable: true, value: {} });",
    '}',
    "if (typeof Intl.getCanonicalLocales !== 'function') {",
    "  Object.defineProperty(Intl, 'getCanonicalLocales', { configurable: true, writable: true, value: getCanonicalLocales });",
    '}',
    '',
  ].join('\n');
  const imports: string[] = [
    './canonical-locales.js',
    path.join(dirs.get(BASE_PACKAGES[1])!, 'polyfill.js'),
  ];
  const dataFiles = new Map<IntlApi, Map<string, string>>();
  const missingLocales = new Map<IntlApi, string[]>();
  for (const { api, package: name } of packages) {
    const dir = dirs.get(name)!;
    imports.push(path.join(dir, 'polyfill.js'));
    const files = new Map<string, string>();
    // The source locale's data loads first: FormatJS falls back to the
    // first locale it has data for.
    const loaded = new Set<string>();
    for (const tag of tags) {
      const dataLocale = findDataLocale(tag, (candidate) =>
        fs.existsSync(path.join(dir, 'locale-data', `${candidate}.js`)),
      );
      if (dataLocale === undefined) {
        missingLocales.set(api, [...(missingLocales.get(api) ?? []), tag]);
        continue;
      }
      const file = path.join(dir, 'locale-data', `${dataLocale}.js`);
      files.set(tag, file);
      if (!loaded.has(file)) {
        loaded.add(file);
        imports.push(file);
      }
    }
    dataFiles.set(api, files);
  }

  const setup: Record<string, unknown> = { sourceLocale: tags[0] };
  if (apis.includes('Collator')) setup['collation'] = collationData(tags);
  const lines = [
    '// Generated by @blotch/rsbuild-plugin-angular-lynx for the `intl` build',
    "// option: FormatJS's polyfills and the app's locales' data, then the",
    "// setup that adds Intl.Collator and uses the device's language and zone.",
    ...imports.map((file) => `import ${JSON.stringify(file)};`),
    `import { setUpIntl } from ${JSON.stringify(runtimePath)};`,
    // JSON.parse of a string reads faster than the same object as code.
    `setUpIntl(JSON.parse(${JSON.stringify(JSON.stringify(setup))}));`,
  ];
  return {
    source: `${lines.join('\n')}\n`,
    canonicalLocalesSource,
    dataFiles,
    missingLocales,
  };
};

/**
 * The runtime half, which the plugin's own build emits next to its index
 * (rslib.config.ts), the way it does the polyfills.
 */
const RUNTIME_PATH = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  'intl-runtime.js',
);

/**
 * Writes `contents` unless the file already has them, so a watch build
 * doesn't rebuild an unchanged module.
 */
const writeIfChanged = (file: string, contents: string): void => {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === contents) {
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents);
};

/**
 * FormatJS's polyfills, which may hold regular expressions with Unicode
 * property escapes the Lynx build's bytecode compiler rejects. Our runtime
 * (`runtimePath`) has some too, so the rule takes it as well.
 */
export const FORMATJS_POLYFILL = /[\\/]@formatjs[\\/][^\\/]+[\\/]polyfill\.js$/;

/**
 * The SWC options that spell out each Unicode property escape (`\p{…}`) as
 * the characters it stands for, and change nothing else: the targets have
 * every other feature the code uses.
 */
export const UNICODE_PROPERTY_REGEX_SWC_OPTIONS = {
  env: {
    targets: 'chrome 120',
    include: ['transform-unicode-property-regex'],
  },
  isModule: true,
};

/**
 * Adds the `Intl` module to the Lynx bundle's preEntry, after the plugin's
 * polyfills (FormatJS's code uses the ES2021+ built-ins they add) and before
 * the app's own (which may load more FormatJS data, such as time zones). Not
 * to the web bundle: browsers have `Intl`.
 *
 * @param polyfillsEntry - The plugin's polyfills, as preEntry lists them.
 */
export const applyIntl = (
  api: RsbuildPluginAPI,
  options: Omit<IntlModuleOptions, 'rootPath' | 'runtimePath'> & {
    readonly polyfillsEntry: string;
    readonly runtimePath?: string;
  },
): void => {
  if (options.apis.length === 0) return;
  const rootPath = api.context.rootPath;
  const runtimePath = options.runtimePath ?? RUNTIME_PATH;
  const module = renderIntlModule({ ...options, rootPath, runtimePath });
  for (const [intlApi, tags] of module.missingLocales) {
    api.logger.warn(
      `Intl.${intlApi}: FormatJS has no data for ${tags.join(', ')}, so it formats ${tags.length === 1 ? 'it' : 'them'} in the source locale.`,
    );
  }
  const dir = path.join(
    rootPath,
    'node_modules',
    '.cache',
    'angular-lynx',
    'intl',
  );
  const file = path.join(dir, 'intl.js');
  writeIfChanged(
    path.join(dir, 'canonical-locales.js'),
    module.canonicalLocalesSource,
  );
  writeIfChanged(file, module.source);
  // The bytecode compiler the build runs on the main thread's script fails
  // the build on any Unicode property escape in a regex literal ("invalid
  // escape sequence in regular expression"), `\p{L}` as much as
  // `\p{Script=Hebrew}`, though PrimJS on the device runs them (from
  // `new RegExp()`). FormatJS's ListFormat has one, and so does our
  // Collator, in the runtime every `intl` list imports (issue #316). SWC
  // spells them out first. The rest of the build doesn't: the main thread's
  // ES2019 target keeps them, and rspeedy's own SWC rule, which runs
  // `transform-unicode-property-regex`, skips JavaScript in `node_modules`,
  // where both are in an app. (In this repository the runtime isn't, which
  // is how #316 got past the examples.)
  api.modifyBundlerChain((chain, { environment }) => {
    if (environment.name !== 'lynx') return;
    chain.module
      .rule('intl-unicode-property-regex')
      .test([FORMATJS_POLYFILL, runtimePath])
      .enforce('pre')
      .use('swc')
      .loader('builtin:swc-loader')
      .options(UNICODE_PROPERTY_REGEX_SWC_OPTIONS);
  });
  api.modifyEnvironmentConfig((config, { name }) => {
    if (name !== 'lynx') return;
    const preEntry = [config.source.preEntry ?? []].flat();
    const index = preEntry.indexOf(options.polyfillsEntry);
    preEntry.splice(index + 1, 0, file);
    config.source.preEntry = preEntry;
  });
};
